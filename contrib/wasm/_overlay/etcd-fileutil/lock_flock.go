// js/wasm replacement for etcd's flock-based file lock. A wasm kcp runs as a
// single-instance, single-process control plane, so advisory file locks are
// not meaningful.
package fileutil

import "os"

func flockTryLockFile(path string, flag int, perm os.FileMode) (*LockedFile, error) {
	f, err := os.OpenFile(path, flag, perm)
	if err != nil {
		return nil, err
	}
	return &LockedFile{f}, nil
}

func flockLockFile(path string, flag int, perm os.FileMode) (*LockedFile, error) {
	f, err := os.OpenFile(path, flag, perm)
	if err != nil {
		return nil, err
	}
	return &LockedFile{f}, nil
}
